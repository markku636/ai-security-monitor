const CONTRACT = path.resolve(__dirname, '../../../contract');
const load = (name: string) => JSON.parse(fs.readFileSync(path.join(CONTRACT, name), 'utf8'));

function post(pathname: string, body: unknown, opts: { key?: string; gzip?: boolean; headers?: Record<string, string> } = {}) {
  const raw = Buffer.from(JSON.stringify(body));
  const payload = opts.gzip ? zlib.gzipSync(raw) : raw;
  const headers: Record<string, string> = { 'content-type': 'application/json', ...(opts.headers ?? {}) };
  if (opts.key !== '') headers.authorization = `Bearer ${opts.key ?? 'client-a'}`;
  if (opts.gzip) headers['content-encoding'] = 'gzip';
  return new Request(`http://localhost:3000${pathname}`, { method: 'POST', headers, body: payload });
}

let db: DB;

beforeAll(async () => {
  db = await createTestDb();
});

beforeEach(() => {
  process.env.ASA_HUB_ADMIN_SECRET = 'test-admin';
  process.env.ASA_HUB_CLIENT_SECRETS = 'client-a';
  process.env.ASA_HUB_INGEST_MIN_INTERVAL_MS = '0';
  process.env.ASA_HUB_SNAPSHOT_MIN_INTERVAL_MS = '0';
  delete process.env.ASA_HUB_PUBLIC_DASHBOARD;
  resetEnvForTests();
  resetThrottleForTests();
  resetRateLimitsForTests();
});

