describe('ingest', () => {
  it('requires a client key', async () => {
    const r = await register(post('/api/v1/agents/register', load('register.v1.json'), { key: '' }));
    expect(r.status).toBe(401);
    const w = await register(post('/api/v1/agents/register', load('register.v1.json'), { key: 'wrong' }));
    expect(w.status).toBe(401);
  });

  it('register → report (gzip) → duplicate → resolve', async () => {
    const reg = await register(post('/api/v1/agents/register', load('register.v1.json')));
    expect(reg.status).toBe(200);
    const rb = await reg.json();
    expect(rb.agent_id).toBe('0f8e5a52-1c3b-4b8e-9d7a-2b1f00c0ffee');
    expect(rb.hub.max_report_bytes).toBe(4194304);

    const rep = load('report.v1.json');
    const r1 = await report(post('/api/v1/ingest/report', rep, { gzip: true }));
    expect(r1.status).toBe(200);
    const b1 = await r1.json();
    expect(b1.duplicate).toBe(false);
    expect(b1.findings.new).toBe(2);

    const dup = await (await report(post('/api/v1/ingest/report', rep))).json();
    expect(dup.duplicate).toBe(true);

    const hits = await db.select().from(intelHits);
    expect(hits).toHaveLength(1);
    expect(hits[0].vendor).toBe('abuse.ch');
    expect(hits[0].sourceUrl).toContain('feodotracker');

    const a = (await db.select().from(agents).where(eq(agents.id, rep.agent.id)))[0];
    expect(a.sevCounts.critical).toBe(2);
    expect(a.openFindings).toBe(2);
    expect(a.score?.overall).toBe(52);

    // 第二份報告：只剩 intel finding → ports finding 應被判已解決。
    const rep2 = structuredClone(rep);
    rep2.report_id = '8e4a2c3b-1d5f-4a6b-9c7d-0e1f2a3b4c5d';
    rep2.finished_at = '2026-10-16T10:30:00Z';
    rep2.findings = rep.findings.filter((f: { scanner: string }) => f.scanner === 'intel');
    const b2 = await (await report(post('/api/v1/ingest/report', rep2))).json();
    expect(b2.findings).toMatchObject({ new: 0, resolved: 1, unchanged: 1 });
    const portRow = (await db.select().from(findings).where(eq(findings.scanner, 'ports')))[0];
    expect(portRow.status).toBe('resolved');

    // 第三份：ports finding 又出現 → 重新開啟。
    const rep3 = structuredClone(rep);
    rep3.report_id = '9f5b3d4c-2e6a-4b7c-8d9e-1f2a3b4c5d6e';
    const b3 = await (await report(post('/api/v1/ingest/report', rep3))).json();
    expect(b3.findings.reopened).toBe(1);
  });

  it('snapshot stores connections and aggregates destinations', async () => {
    await register(post('/api/v1/agents/register', load('register.v1.json')));
    const snap = load('snapshot.v1.json');
    const s1 = await (await snapshot(post('/api/v1/ingest/snapshot', snap))).json();
    expect(s1).toMatchObject({ ok: true, stored: 1, dangerous: 1, destinations: 1 });
    await snapshot(post('/api/v1/ingest/snapshot', snap));
    const conns = await db.select().from(connections);
    expect(conns).toHaveLength(1);
    expect(conns[0].intelFeedIds).toEqual(['abusech-feodo']);
    expect(conns[0].country).toBe('NL');
    const d = await db.select().from(destinations);
    expect(d[0]).toMatchObject({ remoteIp: '203.0.113.66', worstVerdict: 'dangerous', seenCount: 2 });
  });

  it('snapshot from an unregistered agent is refused', async () => {
    const snap = load('snapshot.v1.json');
    snap.agent_id = 'never-registered';
    const r = await snapshot(post('/api/v1/ingest/snapshot', snap));
    expect(r.status).toBe(409);
  });

  it('heartbeat updates a known agent and 404s for unknown ones', async () => {
    await register(post('/api/v1/agents/register', load('register.v1.json')));
    const ok = await heartbeat(
      post('/api/v1/agents/me/heartbeat', { agent_id: '0f8e5a52-1c3b-4b8e-9d7a-2b1f00c0ffee', ts: '2026-10-16T09:00:00Z', version: '0.1.1' }),
    );
    expect(ok.status).toBe(200);
    const nope = await heartbeat(post('/api/v1/agents/me/heartbeat', { agent_id: 'ghost', ts: '2026-10-16T09:00:00Z', version: '1' }));
    expect(nope.status).toBe(404);
  });

  it('heartbeat stores update and LAN-advertising status; omitting them keeps the last value', async () => {
    process.env.ASA_HUB_SNAPSHOT_MIN_INTERVAL_MS = '0';
    resetEnvForTests();
    const ID = '0f8e5a52-1c3b-4b8e-9d7a-2b1f00c0ffee';
    await register(post('/api/v1/agents/register', load('register.v1.json')));
    const hb = (body: Record<string, unknown>) => heartbeat(post('/api/v1/agents/me/heartbeat', { agent_id: ID, ts: new Date().toISOString(), version: '0.3.0', ...body }));
    const r = await hb({
      update: { mode: 'notify', owner: 'agent', latest: '0.4.0', available: true, checked_at: '2026-10-17T08:00:00Z', extra: 'ignored' },
      advertising: { url: 'http://192.168.1.10:8088', state: 'advertising', fingerprint: 'AAAA-BBBB', since: '2026-10-17T08:00:00Z' },
    });
    expect(r.status).toBe(200);
    let [a] = await db.select().from(agents).where(eq(agents.id, ID));
    expect(a.updateInfo).toMatchObject({ mode: 'notify', owner: 'agent', latest: '0.4.0', available: true });
    expect(a.updateInfo).not.toHaveProperty('extra');
    expect(a.advertising).toMatchObject({ url: 'http://192.168.1.10:8088', state: 'advertising', fingerprint: 'AAAA-BBBB' });
    const { advertisers } = await import('@/lib/discovery/status');
    expect(await advertisers(db, 'aaaa-bbbb')).toEqual([expect.objectContaining({ url: 'http://192.168.1.10:8088', fingerprintOk: true })]);
    expect((await advertisers(db, 'CCCC-DDDD'))[0].fingerprintOk).toBe(false);
    // 太久沒心跳的廣播不算
    expect(await advertisers(db, 'AAAA-BBBB', Date.now() + 16 * 60_000)).toEqual([]);
    // 手動上傳的心跳不帶這兩項：保留上次的
    expect((await hb({})).status).toBe(200);
    [a] = await db.select().from(agents).where(eq(agents.id, ID));
    expect(a.updateInfo?.latest).toBe('0.4.0');
    expect(a.advertising?.state).toBe('advertising');
    // 格式不對：拒收
    expect((await hb({ update: { mode: 'x'.repeat(40), owner: 'agent', available: true } })).status).toBe(400);
  });

  it('guards: forbidden keys, gzip bombs, header mismatch, throttling', async () => {
    const bad = await register(post('/api/v1/agents/register', JSON.parse('{"__proto__":{"x":1},"agent":{}}')));
    expect([400]).toContain(bad.status);

    const bomb = zlib.gzipSync(Buffer.alloc(30 * 1024 * 1024, 0x20));
    const r = await report(
      new Request('http://localhost:3000/api/v1/ingest/report', {
        method: 'POST',
        headers: { authorization: 'Bearer client-a', 'content-encoding': 'gzip', 'content-type': 'application/json' },
        body: bomb,
      }),
    );
    expect(r.status).toBe(413);

    const mism = await register(post('/api/v1/agents/register', load('register.v1.json'), { headers: { 'x-asa-agent-id': 'other' } }));
    expect(mism.status).toBe(400);

    process.env.ASA_HUB_INGEST_MIN_INTERVAL_MS = '60000';
    resetEnvForTests();
    const rep = load('report.v1.json');
    rep.report_id = 'aaaaaaaa-bbbb-4ccc-8ddd-eeeeeeeeeeee';
    const first = await report(post('/api/v1/ingest/report', rep));
    expect(first.status).toBe(200);
    rep.report_id = 'bbbbbbbb-bbbb-4ccc-8ddd-eeeeeeeeeeee';
    const second = await report(post('/api/v1/ingest/report', rep));
    expect(second.status).toBe(429);
    expect(Number(second.headers.get('retry-after'))).toBeGreaterThan(0);
    // 已收過的報告重送 → duplicate，不受限流影響（agent outbox 才不會卡死）。
    rep.report_id = 'aaaaaaaa-bbbb-4ccc-8ddd-eeeeeeeeeeee';
    const again = await report(post('/api/v1/ingest/report', rep));
    expect(again.status).toBe(200);
    expect((await again.json()).duplicate).toBe(true);
  });

  it('throttles by report time so a queued backlog drains', async () => {
    process.env.ASA_HUB_INGEST_MIN_INTERVAL_MS = '600000';
    resetEnvForTests();
    const base = load('report.v1.json');
    const t0 = Date.parse(base.finished_at);
    // 三份暫存報告（相隔 10 分鐘）一口氣補送：全部接受。
    for (let i = 0; i < 3; i++) {
      const r = structuredClone(base);
      r.report_id = `cccccccc-0000-4000-8000-00000000000${i}`;
      r.finished_at = new Date(t0 + i * 600_000).toISOString();
      const res = await report(post('/api/v1/ingest/report', r));
      expect(res.status).toBe(200);
    }
    // 時間幾乎相同的另一份 → 429。
    const dupTime = structuredClone(base);
    dupTime.report_id = 'cccccccc-0000-4000-8000-000000000009';
    dupTime.finished_at = new Date(t0 + 2 * 600_000 + 5_000).toISOString();
    expect((await report(post('/api/v1/ingest/report', dupTime))).status).toBe(429);
  });

  it('caps bursts per agent regardless of report timestamps', async () => {
    const base = load('report.v1.json');
    const t0 = Date.parse(base.finished_at);
    let last = 200;
    for (let i = 0; i <= BURST_PER_MINUTE; i++) {
      const r = structuredClone(base);
      r.report_id = `dddddddd-0000-4000-8000-${String(i).padStart(12, '0')}`;
      r.finished_at = new Date(t0 + i * 3_600_000).toISOString();
      r.findings = [];
      last = (await report(post('/api/v1/ingest/report', r))).status;
    }
    expect(last).toBe(429);
  });

  it('lists agents for admins, hides details from public viewers', async () => {
    await register(post('/api/v1/agents/register', load('register.v1.json')));
    const admin = await (
      await listAgentsRoute(new Request('http://localhost:3000/api/v1/agents', { headers: { authorization: 'Bearer test-admin' } }))
    ).json();
    expect(admin.items[0].ips).toBeDefined();
    process.env.ASA_HUB_PUBLIC_DASHBOARD = '1';
    resetEnvForTests();
    const pub = await (await listAgentsRoute(new Request('http://localhost:3000/api/v1/agents'))).json();
    expect(pub.items[0].ips).toBeUndefined();
    const client = await listAgentsRoute(new Request('http://localhost:3000/api/v1/agents', { headers: { authorization: 'Bearer client-a' } }));
    expect(client.status).toBe(401);
  });
});
