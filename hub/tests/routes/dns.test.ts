import fs from 'node:fs';
import path from 'node:path';
import { eq } from 'drizzle-orm';
import { beforeAll, beforeEach, describe, expect, it } from 'vitest';
import { POST as register } from '@/app/api/v1/agents/register/route';
import { POST as dnsIngest } from '@/app/api/v1/ingest/dns/route';
import { dnsDomains, dnsQueries, dnsQueriesHourly } from '@/drizzle/schema';
import { resetRateLimitsForTests } from '@/lib/auth/ratelimit';
import type { DB } from '@/lib/db';
import { fallbackRegistrable } from '@/lib/dns/apply';
import { rollupDns } from '@/lib/dns/rollup';
import { resetEnvForTests } from '@/lib/env';
import { resetThrottleForTests } from '@/lib/ingest/route';
import { DnsBatch } from '@/lib/ingest/schema';
import { createTestDb } from '../helpers/db';

const CONTRACT = path.resolve(__dirname, '../../../contract');
const load = (name: string) => JSON.parse(fs.readFileSync(path.join(CONTRACT, name), 'utf8'));
const A = '0f8e5a52-1c3b-4b8e-9d7a-2b1f00c0ffee';
const minute = 60_000;

function post(body: unknown) {
  return new Request('http://localhost:3000/api/v1/ingest/dns', {
    method: 'POST',
    headers: { 'content-type': 'application/json', authorization: 'Bearer client-a' },
    body: JSON.stringify(body),
  });
}

/** 把契約範例改成最近的時間（固定日期會超過保留天數被略過）。 */
function recent(batch: { records: { ts: string }[] }, now = Date.now()) {
  batch.records = batch.records.map((r, i) => ({ ...r, ts: new Date(now - (10 - i) * minute).toISOString() }));
  return batch;
}

let db: DB;

beforeAll(async () => {
  db = await createTestDb();
  process.env.ASA_HUB_ADMIN_SECRET = 'test-admin';
  process.env.ASA_HUB_CLIENT_SECRETS = 'client-a';
  resetEnvForTests();
  const r = await register(
    new Request('http://localhost:3000/api/v1/agents/register', {
      method: 'POST',
      headers: { 'content-type': 'application/json', authorization: 'Bearer client-a' },
      body: JSON.stringify(load('register.v1.json')),
    }),
  );
  expect(r.status).toBe(200);
});

beforeEach(() => {
  process.env.ASA_HUB_ADMIN_SECRET = 'test-admin';
  process.env.ASA_HUB_CLIENT_SECRETS = 'client-a';
  process.env.ASA_HUB_SNAPSHOT_MIN_INTERVAL_MS = '0';
  delete process.env.ASA_HUB_DNS_RAW_DAYS;
  resetEnvForTests();
  resetThrottleForTests();
  resetRateLimitsForTests();
});

describe('dns ingest', () => {
  it('accepts the contract fixture generated by the Rust agent, resend overwrites', async () => {
    const batch = recent(load('dns.v1.json'));
    expect(DnsBatch.safeParse(batch).success).toBe(true);
    const r = await dnsIngest(post(batch));
    expect(r.status).toBe(200);
    expect(await r.json()).toMatchObject({ ok: true, stored: 2, stale: 0, domains: 2 });
    const rows = await db.select().from(dnsQueries).where(eq(dnsQueries.agentId, A));
    expect(rows).toHaveLength(2);
    const up = rows.find((x) => x.name === 'updates.example.net')!;
    expect(up).toMatchObject({ registrable: 'example.net', process: 'updater.exe', count: 3, rcode: 'NOERROR', source: 'etw' });
    expect(up.answers).toEqual(['203.0.113.66']);
    expect(rows.find((x) => x.rcode === 'NXDOMAIN')!.process).toBe('');
    // 重送同一批（數字變了）：覆蓋、不重複
    resetThrottleForTests();
    batch.records[0].count = 5;
    expect((await dnsIngest(post(batch))).status).toBe(200);
    const again = await db.select().from(dnsQueries).where(eq(dnsQueries.agentId, A));
    expect(again).toHaveLength(2);
    expect(again.find((x) => x.name === 'updates.example.net')!.count).toBe(5);
    const [d] = await db.select().from(dnsDomains).where(eq(dnsDomains.registrable, 'example.net'));
    expect(d.firstAgentId).toBe(A);
    expect(d.firstProcess).toBe('updater.exe');
  });

  it('rolls up hours idempotently and applies retention', async () => {
    const res = await rollupDns(db);
    expect(res.skipped).toBe(false);
    expect(res.hours).toBeGreaterThanOrEqual(1);
    const h = await db.select().from(dnsQueriesHourly).where(eq(dnsQueriesHourly.registrable, 'example.net'));
    expect(h.reduce((s, x) => s + x.queries, 0)).toBe(5);
    expect(h.flatMap((x) => x.processes)).toContain('updater.exe');
    // 重跑結果一樣
    await rollupDns(db);
    const h2 = await db.select().from(dnsQueriesHourly).where(eq(dnsQueriesHourly.registrable, 'example.net'));
    expect(h2.reduce((s, x) => s + x.queries, 0)).toBe(5);
    // 太舊的紀錄進不來
    process.env.ASA_HUB_DNS_RAW_DAYS = '1';
    resetEnvForTests();
    resetThrottleForTests();
    const old = recent(load('dns.v1.json'), Date.now() - 3 * 86_400_000);
    expect(await (await dnsIngest(post(old))).json()).toMatchObject({ stored: 0, stale: 2 });
  });

  it('rejects bad payloads and unknown agents', async () => {
    expect((await dnsIngest(post({ agent_id: A, records: [] }))).status).toBe(400);
    const bad = recent(load('dns.v1.json'));
    bad.records[0].count = 0;
    expect((await dnsIngest(post(bad))).status).toBe(400);
    const unknown = recent(load('dns.v1.json'));
    unknown.agent_id = 'not-registered';
    expect((await dnsIngest(post(unknown))).status).toBe(409);
  });

  it('falls back to the last two labels without a registrable domain', () => {
    expect(fallbackRegistrable('a.b.Example.com.')).toBe('example.com');
    expect(fallbackRegistrable('localhost')).toBe('localhost');
  });
});
