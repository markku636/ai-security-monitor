describe('metrics ingest', () => {
  it('accepts the contract fixture generated by the Rust agent', async () => {
    const batch = load('metrics.v1.json');
    expect(MetricsBatch.safeParse(batch).success).toBe(true);
    // 契約範例是固定日期：改成最近的時間，免得超過原始資料保留天數被略過
    batch.samples = batch.samples.map((s: { ts: string }, i: number) => ({ ...s, ts: new Date(Date.now() - (120 - i) * minute).toISOString() }));
    const r = await metrics(post(batch, { gzip: true }));
    expect(r.status).toBe(200);
    const b = await r.json();
    expect(b).toMatchObject({ ok: true, stored: 2, duplicate: 0, stale: 0, performance: true });
    const rows = await db.select().from(hostMetrics).where(eq(hostMetrics.agentId, A));
    const withPerf = rows.find((x) => x.perf)!;
    expect(withPerf.cpuPct).toBe(23.5);
    expect(withPerf.diskUsedPct).toBeCloseTo(80.67, 1);
    expect(withPerf.topCpu?.[0]).toMatchObject({ name: 'chrome.exe', count: 23, cpu: 11.2 });
    expect(rows.find((x) => !x.perf)?.processes?.[0]).toEqual({ name: 'chrome.exe', rx: 15_728_640, tx: 1_048_576 });
    const [a] = await db.select().from(agents).where(eq(agents.id, A));
    expect(a.perfEnabled).toBe(true);
    expect(a.metricsAt).not.toBeNull();
    // 重送同一批：不重複計算
    resetThrottleForTests();
    const again = await (await metrics(post(batch))).json();
    expect(again).toMatchObject({ stored: 0, duplicate: 2 });
  });

  it('rejects bad payloads, unknown agents and keeps old samples out', async () => {
    const bad = await metrics(post({ agent_id: A, performance: false, samples: [] }));
    expect(bad.status).toBe(400);
    const neg = await metrics(post({ agent_id: A, performance: false, samples: [{ ...samples(1, Date.now())[0], net: { rx_bytes: -1, tx_bytes: 0 } }] }));
    expect(neg.status).toBe(400);
    const cpu = samples(1, Date.now(), { cpu: () => 150 });
    expect((await metrics(post({ agent_id: A, performance: true, samples: cpu }))).status).toBe(400);
    const unknown = await metrics(post({ agent_id: 'not-registered', performance: false, samples: samples(1, Date.now()) }));
    expect(unknown.status).toBe(409);
    const old = await (await metrics(post({ agent_id: A, performance: false, samples: [{ ...samples(1, Date.now())[0], ts: new Date(Date.now() - 30 * 86_400_000).toISOString() }] }))).json();
    expect(old).toMatchObject({ stored: 0, stale: 1 });
    const noKey = await metrics(new Request('http://localhost:3000/api/v1/ingest/metrics', { method: 'POST', headers: { 'content-type': 'application/json' }, body: '{}' }));
    expect(noKey.status).toBe(401);
  });
});

describe('metrics findings, queries and rollup', () => {
  it('judge(): disk ≥ 90% and 15 minutes of CPU ≥ 90% open findings; recovery clears them', () => {
    const now = Date.now();
    const rows = (cpu: number[], used = 95) =>
      cpu.map((c, i) => ({ at: new Date(now - (cpu.length - 1 - i) * minute), intervalS: 60, cpuPct: c, disks: [{ mount: 'C:\\', used, total: 100 }] }));
    const hot = judge(rows(Array(16).fill(97)));
    expect(hot.open.map((c) => c.rule).sort()).toEqual(['metrics.cpu_sustained', 'metrics.disk_full']);
    // 只有 10 分鐘：還不算
    expect(judge(rows(Array(10).fill(97), 10)).open).toHaveLength(0);
    // 中間有一分鐘掉下來：不算連續
    const dip = Array(16).fill(97);
    dip[8] = 50;
    expect(judge(rows(dip, 10)).open).toHaveLength(0);
    expect(judge(rows(Array(16).fill(85), 10)).cpuClear).toBe(false);
    expect(judge(rows(Array(16).fill(20), 10)).cpuClear).toBe(true);
  });

  it('performance-on host: findings open, then resolve when performance is turned off', async () => {
    const now = Date.now();
    const r = await metrics(post({ agent_id: A, performance: true, samples: samples(20, now, { cpu: () => 96, diskUsed: 95 * 1024 ** 3 }) }));
    expect(r.status).toBe(200);
    const open = await db.select().from(findings).where(and(eq(findings.agentId, A), eq(findings.scanner, 'metrics'), eq(findings.status, 'open')));
    expect(open.map((f) => f.rule).sort()).toEqual(['metrics.cpu_sustained', 'metrics.disk_full']);
    expect(open.every((f) => f.severity === 'low')).toBe(true);
    const alerts = await perfAlerts();
    expect(alerts.find((a) => a.agentId === A)?.reasons.sort()).toEqual(['cpu', 'disk']);

    resetThrottleForTests();
    const off = await metrics(post({ agent_id: A, performance: false, samples: samples(1, now + minute) }));
    expect(off.status).toBe(200);
    const still = await db.select().from(findings).where(and(eq(findings.agentId, A), eq(findings.scanner, 'metrics'), eq(findings.status, 'open')));
    expect(still).toHaveLength(0);
    const [a] = await db.select().from(agents).where(eq(agents.id, A));
    expect(a.perfEnabled).toBe(false);
  });

  it('queries: bandwidth, ranking, interfaces, processes, perf series and latest values', async () => {
    const bw = await bandwidthSeries('1h');
    expect(bw.hasData).toBe(true);
    expect(bw.points.length).toBeGreaterThanOrEqual(60);
    const withData = bw.points.filter((p) => p.rx != null);
    expect(withData.length).toBeGreaterThan(5);
    // 每分鐘 1 MB → 每秒約 17 KB
    expect(withData[1].rx).toBeCloseTo(1_048_576 / 60, 0);
    expect(bw.totalRx).toBeGreaterThan(20 * 1_048_576);

    const rank = await hostTrafficRanking();
    expect(rank[0]).toMatchObject({ agentId: A, hostname: 'demo-host' });
    expect(rank[0].rx24h).toBeGreaterThan(0);
    expect(rank[0].rx7d).toBeGreaterThanOrEqual(rank[0].rx24h);

    const ifs = await interfaceBreakdown('24h', A);
    expect(ifs.map((i) => i.name)).toContain('eth0');
    expect(ifs.find((i) => i.name === 'docker0')?.virtual).toBe(true);
    expect(ifs.find((i) => i.name === 'vEthernet (WSL)')?.virtual).toBe(true);

    const procs = await processTraffic('24h');
    expect(procs.hostsWithData).toBe(1);
    expect(procs.rows.map((p) => p.name)).toEqual(expect.arrayContaining(['curl', 'chrome.exe']));

    const perf = await hostPerfSeries(A, '1h');
    expect(perf.hasPerf).toBe(true);
    const p = perf.points.filter((x) => x.cpu != null);
    expect(p.length).toBeGreaterThan(5);
    expect(p[p.length - 2].memPct).toBeCloseTo(50, 0);
    expect(p[p.length - 2].battery).toBe(64);

    const latest = await latestPerf(A);
    expect(latest?.topCpu[0]).toMatchObject({ name: 'java', pid: 4242 });
    expect(latest?.disks[0].mount).toBe('/');

    const sum = await trafficSummary();
    expect(sum).toMatchObject({ hosts24h: 1, reporting: 1, perfEnabled: 0 });
    expect(sum.rx24h).toBeGreaterThan(0);
  });

  it('hourly rollup is idempotent, feeds the 7-day charts and applies retention', async () => {
    const first = await rollupMetrics(db);
    expect(first.skipped).toBe(false);
    expect(first.hours).toBeGreaterThanOrEqual(1);
    const n1 = await hourlyCount(A);
    const [h1] = await db.select().from(hostMetricsHourly).where(eq(hostMetricsHourly.agentId, A)).limit(1);
    // 再跑一次：只會重算最近幾分鐘收到的那個小時，結果不變
    const second = await rollupMetrics(db);
    expect(second.skipped).toBe(false);
    expect(await hourlyCount(A)).toBe(n1);
    // 強制重算（把水位線往回撥）：結果一樣
    await db.update(settings).set({ value: new Date(0).toISOString() }).where(eq(settings.key, 'metrics.rollup_watermark'));
    await rollupMetrics(db);
    const [h2] = await db.select().from(hostMetricsHourly).where(and(eq(hostMetricsHourly.agentId, A), eq(hostMetricsHourly.hour, h1.hour)));
    expect(h2.rxBytes).toBe(h1.rxBytes);
    expect(h2.samples).toBe(h1.samples);

    const week = await bandwidthSeries('7d');
    expect(week.hasData).toBe(true);
    expect(week.totalRx).toBe((await bandwidthSeries('24h')).totalRx);
    const perf7 = await hostPerfSeries(A, '7d');
    expect(perf7.hasPerf).toBe(true);

    // 保留期限：原始資料只留 1 天、彙總留 1 天 → 2 天後全部清掉
    process.env.ASA_HUB_METRICS_RAW_DAYS = '1';
    process.env.ASA_HUB_METRICS_HOURLY_DAYS = '1';
    resetEnvForTests();
    const later = await rollupMetrics(db, new Date(Date.now() + 2 * 86_400_000));
    expect(later.deletedRaw).toBeGreaterThan(0);
    expect(later.deletedHourly).toBeGreaterThan(0);
    expect(await hourlyCount(A)).toBe(0);
  });

  it('aggregateHour sums bytes, merges interfaces/processes and averages CPU', () => {
    const base = {
      agentId: A,
      intervalS: 60,
      rxBytes: 100,
      txBytes: 10,
      interfaces: [{ name: 'eth0', virtual: false, rx: 100, tx: 10 }],
      processes: [{ name: 'curl', rx: 50, tx: 5 }],
      perf: true,
      cpuPct: 20,
      cpuCores: 4,
      memUsed: 4,
      memTotal: 8,
      swapUsed: 0,
      swapTotal: 0,
      disks: [],
      diskUsedPct: 10,
      diskRead: 1,
      diskWrite: 2,
      load1: null,
      uptimeS: 1,
      topCpu: [],
      topMem: [],
      battery: { percent: 50, charging: false },
      receivedAt: new Date(),
    };
    const hour = new Date('2026-10-17T09:00:00Z');
    const agg = aggregateHour(A, hour, [
      { ...base, at: new Date('2026-10-17T09:01:00Z') },
      { ...base, at: new Date('2026-10-17T09:02:00Z'), cpuPct: 60, battery: { percent: 40, charging: false }, processes: null },
    ]);
    expect(agg).toMatchObject({ samples: 2, seconds: 120, rxBytes: 200, txBytes: 20, perfSamples: 2, cpuAvg: 40, cpuMax: 60, diskRead: 2, batteryMin: 40, batteryLast: 40 });
    expect(agg.interfaces).toEqual([{ name: 'eth0', virtual: false, rx: 200, tx: 20 }]);
    expect(agg.processes).toEqual([{ name: 'curl', rx: 50, tx: 5 }]);
  });

  it('MCP exposes fleet_traffic and host_performance', async () => {
    const call = async (name: string, args: Record<string, unknown>) => {
      const r = await mcpPost(
        new Request('http://localhost:3000/api/mcp', {
          method: 'POST',
          headers: { authorization: 'Bearer test-admin', 'content-type': 'application/json' },
          body: JSON.stringify({ jsonrpc: '2.0', id: 1, method: 'tools/call', params: { name, arguments: args } }),
        }),
      );
      const b = await r.json();
      return JSON.parse(b.result.content[0].text);
    };
    const list = await (
      await mcpPost(new Request('http://localhost:3000/api/mcp', { method: 'POST', headers: { authorization: 'Bearer test-admin', 'content-type': 'application/json' }, body: JSON.stringify({ jsonrpc: '2.0', id: 1, method: 'tools/list' }) }))
    ).json();
    const names = list.result.tools.map((t: { name: string }) => t.name);
    // 上一個測試把資料清掉了：再送一批
    expect((await metrics(post({ agent_id: A, performance: false, samples: samples(5, Date.now()) }))).status).toBe(200);
    expect(names).toEqual(expect.arrayContaining(['fleet_traffic', 'host_performance']));
    const ft = await call('fleet_traffic', { range: '24h' });
    expect(ft.hosts[0].hostname).toBe('demo-host');
    const hp = await call('host_performance', { agent_id: A, range: '1h' });
    expect(hp.performance_enabled).toBe(false);
    expect(hp.series.samples).toBeGreaterThan(0);
  });
});
