function post(body: unknown, opts: { gzip?: boolean } = {}) {
  const raw = Buffer.from(JSON.stringify(body));
  const headers: Record<string, string> = { 'content-type': 'application/json', authorization: 'Bearer client-a' };
  if (opts.gzip) headers['content-encoding'] = 'gzip';
  return new Request('http://localhost:3000/api/v1/ingest/metrics', { method: 'POST', headers, body: opts.gzip ? zlib.gzipSync(raw) : raw });
}

const minute = 60_000;
/** 從 now 往回 n 分鐘、每分鐘一個樣本（rx 1 MB、tx 0.1 MB；有 perf 時 CPU 用 cpu(i)）。 */
function samples(n: number, now: number, perf?: { cpu: (i: number) => number; diskUsed?: number }) {
  return Array.from({ length: n }, (_, k) => {
    const i = n - 1 - k;
    return {
      ts: new Date(now - i * minute).toISOString(),
      interval_s: 60,
      net: {
        rx_bytes: 1_048_576,
        tx_bytes: 104_857,
        interfaces: [
          { name: 'eth0', virtual: false, rx_bytes: 1_048_576, tx_bytes: 104_857 },
          { name: 'docker0', virtual: true, rx_bytes: 2048, tx_bytes: 1024 },
        ],
        processes: [{ name: 'curl', rx_bytes: 1_000_000, tx_bytes: 100_000 }],
        process_source: 'estats',
      },
      ...(perf
        ? {
            perf: {
              cpu_pct: perf.cpu(i),
              cpu_cores: 4,
              mem_used: 8 * 1024 ** 3,
              mem_total: 16 * 1024 ** 3,
              swap_used: 0,
              swap_total: 2 * 1024 ** 3,
              disks: [{ mount: '/', fs: 'ext4', used: perf.diskUsed ?? 50 * 1024 ** 3, total: 100 * 1024 ** 3 }],
              disk_read_bytes: 600_000,
              disk_write_bytes: 60_000,
              load: [1.5, 1.2, 1.0],
              uptime_s: 86_400,
              boot_time: new Date(now - 86_400_000).toISOString(),
              top_cpu: [{ name: 'java', pid: 4242, count: 1, cpu_pct: 40.5, rss: 2 * 1024 ** 3 }],
              top_mem: [{ name: 'java', pid: 4242, count: 1, cpu_pct: 40.5, rss: 2 * 1024 ** 3 }],
              battery: { percent: 64, charging: true, plugged: true },
            },
          }
        : {}),
    };
  });
}

